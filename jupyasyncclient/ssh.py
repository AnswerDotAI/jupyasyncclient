def ssh_host_block(
    host:str, # SSH Host alias
    *,
    user:str=None, # Optional remote SSH username (`root` for Colab, `solveit` for Solveit)
    identity:str=None, # Optional `ed25519`/`ecdsa` key path (auto-detected if omitted)
    ssh_dir:Path=None, # Directory used for key auto-detection
    proxy_cmd:str=None, # Explicit `ProxyCommand` override
    store:str|Path=None, # Non-default session store path to pass to `jac-ssh --proxy`
)->str:
    "Render an OpenSSH `Host` stanza pointing `ProxyCommand` at `jac-ssh --proxy`."
    key = identity or default_identity(ssh_dir or Path('~/.ssh').expanduser())
    if not proxy_cmd:
        parts = [_proxy_bin(), '--proxy', '--host', shlex.quote(host)]
        if key: parts += ['--identity', shlex.quote(key)]
        if store: parts += ['--store', shlex.quote(str(Path(store).expanduser()))]
