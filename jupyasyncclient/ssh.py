def default_identity(
    ssh_dir:str|Path='~/.ssh', # Directory to scan for non-RSA key pairs
)->str|None:
    "Return the first `id_ed25519` or `id_ecdsa` path whose private and `.pub` files both exist."
    d = Path(ssh_dir).expanduser()
    is_home = d == Path('~/.ssh').expanduser()
    for n in SSH_KEY_NAMES:
        if (d/n).exists() and (d/f'{n}.pub').exists(): return f'~/.ssh/{n}' if is_home else str(d/n)
    return None

def _pubkey_from_private(path:Path)->str:
    if not path.exists(): raise FileNotFoundError(f'SSH key not found: {path}')
    res = subprocess.run(['ssh-keygen', '-y', '-f', str(path)], check=True, capture_output=True, text=True)
    pub = res.stdout.strip()
    if not pub: raise RuntimeError(f'ssh-keygen produced no public key for {path}')
    return pub

def resolve_pubkey(
    identity:str|Path=None, # Explicit public or private key path, or `None` to scan `ssh_dir`
    ssh_dir:str|Path='~/.ssh', # Directory scanned when `identity` is omitted
)->str:
    "Return the OpenSSH public key text to send in the WebSocket upgrade header."
    if identity:
        p = Path(identity).expanduser()
        pub_p, priv_p = (p, p.with_suffix('')) if p.suffix == '.pub' else (p.with_suffix('.pub'), p)
        if pub_p.exists() and (txt := pub_p.read_text().strip()): return txt
        return _pubkey_from_private(priv_p if priv_p.exists() else p)
    d = Path(ssh_dir).expanduser()
    for n in SSH_KEY_NAMES:
        cand = d/f'{n}.pub'
        if cand.exists() and (txt := cand.read_text().strip()): return txt
    raise FileNotFoundError(f'No ed25519 or ecdsa public key found in {d}. Run `ssh-keygen -t ed25519` or pass --identity.')

