def _host_matches(line:str, host:str)->bool:
    toks = line.split('#', 1)[0].split()
    return len(toks) > 1 and toks[0].lower() == 'host' and host in toks[1:]

def _has_ssh_host(cfg:str, host:str)->bool: return any(_host_matches(ln, host) for ln in cfg.splitlines())

def _replace_ssh_host(cfg:str, host:str, block:str)->str:
    lines, out, i = cfg.splitlines(keepends=True), [], 0
    while i < len(lines):
        if _host_matches(lines[i], host):
            out.append(block)
            i += 1
            while i < len(lines):
                toks = lines[i].split('#', 1)[0].split()
                if toks and toks[0].lower() in ('host', 'match'): break
                i += 1
            if i < len(lines) and not block.endswith('\n\n'): out.append('\n')
        else:
            out.append(lines[i])
            i += 1
    return ''.join(out)

