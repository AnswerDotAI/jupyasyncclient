def _explain_handshake_error(status:int, body:bytes)->str:
    snippet = body.decode('utf-8', errors='replace').strip()[:200]
    if status == 400 and 'missing pubkey' in snippet: return 'Server rejected request: missing SSH public key header.'
    if status == 400 and 'unsupported key type' in snippet: return 'Server rejected public key: unsupported key type (use ed25519 or ecdsa).'
    if status == 400: return f'Server rejected SSH request (HTTP 400): {snippet}'
    if status == 401: return 'Authentication failed (HTTP 401): token invalid or expired.'
    if status == 403: return f'Forbidden (HTTP 403): {snippet or "access denied"}'
    if status == 404: return 'Endpoint not found (HTTP 404): server does not expose this SSH WebSocket path.'
    if status == 429: return f'SSH session limit reached (HTTP 429): {snippet}'
    if status == 502: return 'Bad gateway (HTTP 502): upstream SSH server is unreachable.'
    return f'WebSocket upgrade rejected (HTTP {status}): {snippet}'

def bridge_ws(
    ws, # Connected `websockets.sync.client.ClientConnection`
    stdin_fd:int=None, # Input file descriptor (defaults to `sys.stdin.buffer.fileno()`)
    stdout=None, # Binary output stream (defaults to `sys.stdout.buffer`)
)->int:
    "Bridge raw bytes bidirectionally between `stdin_fd`/`stdout` and binary frames on `ws`."
    if stdin_fd is None: stdin_fd = sys.stdin.buffer.fileno()
    if stdout is None: stdout = sys.stdout.buffer
    def _stdin_to_ws():
        try:
            while data := os.read(stdin_fd, 65536): ws.send(data)
        except (OSError, WebSocketException): pass
        finally:
            with suppress(Exception): ws.close()
    threading.Thread(target=_stdin_to_ws, daemon=True).start()
    try:
        for frame in ws:
            if isinstance(frame, str): frame = frame.encode('utf-8')
            stdout.write(frame)
            stdout.flush()
    except (ConnectionClosed, WebSocketException, OSError): pass
    finally:
        with suppress(Exception): ws.close()
    return 0

