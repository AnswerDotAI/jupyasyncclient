def save_ssh_session(
    host:str, # SSH Host alias key
    entry:dict, # Connection fields (`url`, `headers`, `token_file`, `pubkey_header`, etc.)
    store:str|Path=None, # Optional session store path
)->AttrDict:
    "Atomically save `entry` under `host` in the SSH session store (mode `0600`)."
    p = ssh_store_path(store)
    data = load_ssh_sessions(p)
    data[host] = {k: v for k, v in entry.items() if v is not None}
    p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    with atomic_save(p, mode='w') as f: json.dump(data, f, indent=2)
    os.chmod(p, 0o600)
    return AttrDict(data[host])

def get_ssh_session(host:str, store:str|Path=None)->AttrDict|None:
    "Return the saved SSH session for `host`, or `None` if absent."
    entry = load_ssh_sessions(store).get(host)
    return AttrDict(entry) if entry is not None else None

def remove_ssh_session(host:str, store:str|Path=None)->bool:
    "Remove `host` from the SSH session store; return `True` if it existed."
    p = ssh_store_path(store)
    data = load_ssh_sessions(p)
    if host not in data: return False
    del data[host]
    with atomic_save(p, mode='w') as f: json.dump(data, f, indent=2)
    os.chmod(p, 0o600)
    return True

