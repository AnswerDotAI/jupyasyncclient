def proxy_ssh(
    host:str=None, # Saved session alias to load from `store`
    *,
    url:str=None, # Direct WebSocket or HTTP(S) URL (overrides stored session URL)
    identity:str=None, # Path to public or private SSH key
    token:str=None, # Optional `?token=` query parameter
    bearer:str=None, # Optional `Authorization: Bearer` token
    token_file:str|Path=None, # Optional file holding a Bearer token
    headers:dict=None, # Extra HTTP upgrade headers
    pubkey_header:str=None, # Upgrade header name for the SSH public key
    store:str|Path=None, # Optional session store path
    stdin_fd:int=None, # Override input fd (for testing)
    stdout=None, # Override output stream (for testing)
)->int:
    "Connect to an SSH-over-WebSocket endpoint and bridge stdio for OpenSSH `ProxyCommand`."
    sess = get_ssh_session(host, store=store) if host else None
    if host and not sess and not url:
        print(f'[jac-ssh] session {host!r} not found in {ssh_store_path(store)}.', file=sys.stderr)
        return 2
    sess = sess or AttrDict()
    target = url or sess.get('url')
    if not target:
        print('[jac-ssh] no target URL provided or saved.', file=sys.stderr)
        return 2
    ws_url = gateway_ws_url(target, token=token or sess.get('token'))
    hdrs = dict(sess.get('headers') or {})
    if headers: hdrs.update(headers)
    try:
        tok = bearer or sess.get('bearer') or (_read_token_file(tf) if (tf := token_file or sess.get('token_file')) else None)
        if tok: hdrs['Authorization'] = f'Bearer {tok}'
        hdrs[pubkey_header or sess.get('pubkey_header') or COLAB_PUBKEY_HEADER] = resolve_pubkey(identity or sess.get('identity'))
    except Exception as e:
        print(f'[jac-ssh] {e}', file=sys.stderr)
        return 2
    try:
        with ws_connect(ws_url, additional_headers=hdrs, compression=None, max_size=None, ping_interval=20) as ws:
            return bridge_ws(ws, stdin_fd=stdin_fd, stdout=stdout)
    except InvalidStatus as e:
        print(f'[jac-ssh] {_explain_handshake_error(e.response.status_code, e.response.body or b"")}', file=sys.stderr)
        return 1
    except (WebSocketException, OSError) as e:
        print(f'[jac-ssh] WebSocket connection failed: {e}', file=sys.stderr)
        return 1

